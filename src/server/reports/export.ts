import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";
import type { PerformanceReport } from "@/server/reports/performance";
import type { SourceReport } from "@/server/reports/sources";
import type { PunctualityReport } from "@/server/reports/punctuality";
import type { RawReport } from "@/server/reports/raw";

/**
 * RP-01 — Excel and PDF export.
 *
 * THE SHAPE OF THIS FILE IS THE POINT. Four reports times two formats is eight
 * exporters if written directly, and eight places for a column to be renamed in
 * seven of them. Instead every report is first flattened into one neutral
 * `ExportDocument` (a title, some meta, and sections that are either a summary
 * block or a table), and there are exactly TWO renderers — one for .xlsx, one
 * for .pdf. Adding a report means adding a shaper, not touching either renderer.
 *
 * The numbers are never recomputed here. This module receives Dev A's report
 * payloads exactly as the screen received them, so an export cannot disagree
 * with the screen it was exported from — which is the whole reason we agreed a
 * contract before building.
 */

export const REPORT_KINDS = ["performance", "sources", "punctuality", "raw"] as const;
export type ReportKind = (typeof REPORT_KINDS)[number];

export const REPORT_TITLES: Record<ReportKind, string> = {
  performance: "Performance report",
  sources: "Lead source report",
  punctuality: "Punctuality report",
  raw: "Raw call data",
};

export interface ExportColumn {
  header: string;
  key: string;
  /** Relative weight: the PDF scales these to the page, Excel uses them as characters. */
  width: number;
  align?: "left" | "right";
}

export type ExportSection =
  | { type: "summary"; title: string; items: { label: string; value: string }[] }
  | {
      type: "table";
      title: string;
      columns: ExportColumn[];
      rows: Record<string, string | number | null>[];
      note?: string;
    };

export interface ExportDocument {
  title: string;
  /** Dev A's server-rendered range label, frozen at generation time. */
  subtitle: string;
  meta: { label: string; value: string }[];
  sections: ExportSection[];
}

export interface ExportContext {
  rangeLabel: string;
  generatedAt: Date;
  generatedBy: string;
  filters: { agent?: string | null; source?: string | null; disposition?: string | null };
}

// --- formatting -------------------------------------------------------------

/** 4210 -> "1h 10m 10s". A cell holding raw seconds is unreadable to a human. */
export function hms(totalSec: number): string {
  const s = Math.max(0, Math.round(totalSec));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  if (h > 0) return `${h}h ${m}m ${sec}s`;
  if (m > 0) return `${m}m ${sec}s`;
  return `${sec}s`;
}

function pct(n: number): string {
  return `${n.toFixed(1)}%`;
}

function dateTime(iso: string): string {
  return new Date(iso).toLocaleString("en-GB", { dateStyle: "short", timeStyle: "short" });
}

function metaOf(ctx: ExportContext): { label: string; value: string }[] {
  return [
    { label: "Period", value: ctx.rangeLabel },
    { label: "Generated", value: ctx.generatedAt.toLocaleString("en-GB") },
    { label: "Generated by", value: ctx.generatedBy },
    { label: "Agent filter", value: ctx.filters.agent || "All agents" },
    { label: "Source filter", value: ctx.filters.source || "All sources" },
    { label: "Outcome filter", value: ctx.filters.disposition || "All outcomes" },
  ];
}

// --- shapers, one per report ------------------------------------------------

export function performanceDocument(r: PerformanceReport, ctx: ExportContext): ExportDocument {
  const outcomeRows = Object.entries(r.outcomes).map(([code, count]) => ({
    outcome: code === "undispositioned" ? "No outcome recorded" : code.replace(/_/g, " "),
    count,
    share: r.totals.callsMade > 0 ? pct((count / r.totals.callsMade) * 100) : "0.0%",
  }));

  return {
    title: REPORT_TITLES.performance,
    subtitle: ctx.rangeLabel,
    meta: metaOf(ctx),
    sections: [
      {
        type: "summary",
        title: "Totals",
        items: [
          { label: "Leads assigned", value: String(r.totals.leadsAssigned) },
          { label: "Leads worked", value: String(r.totals.leadsWorked) },
          { label: "Calls made", value: String(r.totals.callsMade) },
          { label: "Talk time", value: hms(r.totals.talkTimeSec) },
          { label: "Average talk time", value: hms(r.totals.avgTalkSec) },
          { label: "Callbacks set", value: String(r.totals.callbacksSet) },
          { label: "Callbacks completed", value: String(r.totals.callbacksDone) },
          { label: "Qualified", value: String(r.totals.qualified) },
          { label: "Conversion", value: pct(r.totals.conversionPct) },
        ],
      },
      {
        type: "table",
        title: "By agent",
        columns: [
          { header: "Agent", key: "fullName", width: 24 },
          { header: "Leads worked", key: "leadsWorked", width: 13, align: "right" },
          { header: "Calls", key: "calls", width: 9, align: "right" },
          { header: "Talk time", key: "talkTime", width: 13, align: "right" },
          { header: "Avg talk", key: "avgTalk", width: 11, align: "right" },
          { header: "Qualified", key: "qualified", width: 11, align: "right" },
          { header: "Conversion", key: "conversion", width: 12, align: "right" },
          { header: "Callbacks set", key: "callbacksSet", width: 13, align: "right" },
          { header: "Callbacks done", key: "callbacksDone", width: 14, align: "right" },
        ],
        rows: r.byAgent.map((a) => ({
          fullName: a.fullName,
          leadsWorked: a.leadsWorked,
          calls: a.calls,
          talkTime: hms(a.talkTimeSec),
          avgTalk: hms(a.avgTalkSec),
          qualified: a.qualified,
          conversion: pct(a.conversionPct),
          callbacksSet: a.callbacksSet,
          callbacksDone: a.callbacksDone,
        })),
        note: "Conversion is qualified divided by leads worked — a lead carrying an outcome, not a dialled attempt.",
      },
      {
        type: "table",
        title: "Outcome mix",
        columns: [
          { header: "Outcome", key: "outcome", width: 24 },
          { header: "Calls", key: "count", width: 10, align: "right" },
          { header: "Share of calls", key: "share", width: 14, align: "right" },
        ],
        rows: outcomeRows,
      },
      {
        type: "table",
        title: "By day",
        columns: [
          { header: "Date", key: "date", width: 14 },
          { header: "Calls", key: "calls", width: 10, align: "right" },
          { header: "Leads worked", key: "leadsWorked", width: 13, align: "right" },
          { header: "Qualified", key: "qualified", width: 11, align: "right" },
        ],
        rows: r.byDay.map((d) => ({ ...d })),
      },
    ],
  };
}

export function sourcesDocument(r: SourceReport, ctx: ExportContext): ExportDocument {
  const columns: ExportColumn[] = [
    { header: "Source", key: "source", width: 26 },
    { header: "Imported", key: "imported", width: 11, align: "right" },
    { header: "Owned now", key: "assigned", width: 12, align: "right" },
    { header: "Worked", key: "worked", width: 10, align: "right" },
    { header: "Contacted", key: "contacted", width: 11, align: "right" },
    { header: "Qualified", key: "qualified", width: 11, align: "right" },
    { header: "Do Not Call now", key: "doNotCall", width: 15, align: "right" },
    { header: "Worked %", key: "workedPct", width: 11, align: "right" },
    { header: "Conversion", key: "conversionPct", width: 12, align: "right" },
  ];

  const rows: Record<string, string | number | null>[] = r.sources.map((s) => ({
    source: s.source,
    imported: s.imported,
    assigned: s.assigned,
    worked: s.worked,
    contacted: s.contacted,
    qualified: s.qualified,
    doNotCall: s.doNotCall,
    workedPct: pct(s.workedPct),
    conversionPct: pct(s.conversionPct),
  }));

  rows.push({
    source: "TOTAL",
    imported: r.totals.imported,
    assigned: r.totals.assigned,
    worked: r.totals.worked,
    contacted: r.totals.contacted,
    qualified: r.totals.qualified,
    doNotCall: r.totals.doNotCall,
    workedPct: pct(r.totals.workedPct),
    conversionPct: pct(r.totals.conversionPct),
  });

  return {
    title: REPORT_TITLES.sources,
    subtitle: ctx.rangeLabel,
    meta: metaOf(ctx),
    sections: [
      {
        type: "table",
        title: "By source",
        columns,
        rows,
        note: "Imported, worked, contacted and qualified count what happened inside the period. Owned now and Do Not Call now are current state and do not move with the period; Owned now counts every lead that still has an agent attached, closed ones included. Conversion is qualified divided by worked, never by imported — a source with a large untouched backlog is unworked, not underperforming. Worked % compares work done in the period against leads imported in the same period.",
      },
    ],
  };
}

