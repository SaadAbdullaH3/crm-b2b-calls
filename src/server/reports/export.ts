// --- renderers --------------------------------------------------------------

export async function toXlsx(doc: ExportDocument): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.created = new Date();

  const cover = wb.addWorksheet("Report");
  cover.columns = [{ width: 24 }, { width: 60 }];
  cover.addRow([doc.title]).font = { bold: true, size: 16 };
  cover.addRow([doc.subtitle]).font = { size: 12, color: { argb: "FF555555" } };
  cover.addRow([]);
  for (const m of doc.meta) {
    const row = cover.addRow([m.label, m.value]);
    row.getCell(1).font = { bold: true };
  }

  for (const section of doc.sections) {
    if (section.type === "summary") {
      cover.addRow([]);
      cover.addRow([section.title]).font = { bold: true, size: 13 };
      for (const item of section.items) {
        const row = cover.addRow([item.label, item.value]);
        row.getCell(1).font = { bold: true };
      }
      continue;
    }

    // Excel sheet names cannot exceed 31 characters or contain : \ / ? * [ ]
    const name = section.title.replace(/[:\\/?*[\]]/g, " ").slice(0, 31);
    const ws = wb.addWorksheet(name);
    ws.columns = section.columns.map((c) => ({ header: c.header, key: c.key, width: c.width }));
    ws.getRow(1).font = { bold: true };
    ws.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFEFEFEF" } };
    ws.views = [{ state: "frozen", ySplit: 1 }];
    ws.autoFilter = {
      from: { row: 1, column: 1 },
      to: { row: 1, column: section.columns.length },
    };

    for (const row of section.rows) {
      ws.addRow(row);
    }
    for (const [i, c] of section.columns.entries()) {
      if (c.align === "right") ws.getColumn(i + 1).alignment = { horizontal: "right" };
    }
    if (section.note) {
      ws.addRow([]);
      ws.addRow([section.note]).font = { italic: true, color: { argb: "FF555555" } };
    }
  }

  const buf = await wb.xlsx.writeBuffer();
  return Buffer.from(buf);
}

const PDF_MARGIN = 32;
const ROW_HEIGHT = 13;

export function toPdf(doc: ExportDocument): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    // Landscape because every one of these reports is a wide table; portrait
    // forces either a microscopic font or a column off the page.
    const pdf = new PDFDocument({ size: "A4", layout: "landscape", margin: PDF_MARGIN });
    const chunks: Buffer[] = [];
    pdf.on("data", (c: Buffer) => chunks.push(c));
    pdf.on("end", () => resolve(Buffer.concat(chunks)));
    pdf.on("error", reject);

    const pageWidth = pdf.page.width - PDF_MARGIN * 2;
    const bottom = pdf.page.height - PDF_MARGIN;

    pdf.font("Helvetica-Bold").fontSize(18).fillColor("#111111").text(doc.title);
    pdf.moveDown(0.2);
    pdf.font("Helvetica").fontSize(11).fillColor("#555555").text(doc.subtitle);
    pdf.moveDown(0.6);

    pdf.fontSize(8).fillColor("#444444");
    pdf.text(doc.meta.map((m) => `${m.label}: ${m.value}`).join("    |    "), { width: pageWidth });
    pdf.moveDown(0.8);

    const drawHeader = (columns: ExportColumn[], xs: number[], widths: number[]) => {
      const y = pdf.y;
      pdf.rect(PDF_MARGIN, y - 2, pageWidth, 16).fill("#EFEFEF");
      pdf.fillColor("#111111").font("Helvetica-Bold").fontSize(8);
      columns.forEach((c, i) => {
        pdf.text(c.header, xs[i], y + 2, {
          width: widths[i] - 4,
          align: c.align ?? "left",
          lineBreak: false,
          ellipsis: true,
        });
      });
      pdf.y = y + 16;
    };

    for (const section of doc.sections) {
      if (pdf.y > bottom - 80) pdf.addPage();

      pdf.font("Helvetica-Bold").fontSize(12).fillColor("#111111").text(section.title, PDF_MARGIN, pdf.y);
      pdf.moveDown(0.3);

      if (section.type === "summary") {
        const half = Math.ceil(section.items.length / 2);
        const colWidth = pageWidth / 2;
        const top = pdf.y;
        pdf.fontSize(9).fillColor("#222222");
        section.items.forEach((item, i) => {
          const col = i < half ? 0 : 1;
          const rowIndex = i < half ? i : i - half;
          const y = top + rowIndex * 14;
          pdf.font("Helvetica").text(item.label, PDF_MARGIN + col * colWidth, y, {
            width: colWidth * 0.6,
            lineBreak: false,
            ellipsis: true,
          });
          pdf
            .font("Helvetica-Bold")
            .text(item.value, PDF_MARGIN + col * colWidth + colWidth * 0.6, y, {
              width: colWidth * 0.35,
              lineBreak: false,
              ellipsis: true,
            });
        });
        pdf.y = top + half * 14 + 10;
        continue;
      }

      const totalWeight = section.columns.reduce((sum, c) => sum + c.width, 0);
      const widths = section.columns.map((c) => (c.width / totalWeight) * pageWidth);
      const xs: number[] = [];
      let x = PDF_MARGIN;
      for (const w of widths) {
        xs.push(x);
        x += w;
      }

      drawHeader(section.columns, xs, widths);
      pdf.font("Helvetica").fontSize(8).fillColor("#222222");

      section.rows.forEach((row, index) => {
        if (pdf.y > bottom - 24) {
          pdf.addPage();
          drawHeader(section.columns, xs, widths);
          pdf.font("Helvetica").fontSize(8).fillColor("#222222");
        }
        const y = pdf.y;
        if (index % 2 === 1) {
          pdf.rect(PDF_MARGIN, y - 2, pageWidth, ROW_HEIGHT).fill("#F7F7F7");
          pdf.fillColor("#222222");
        }
        section.columns.forEach((c, i) => {
          const value = row[c.key];
          pdf.text(value === null || value === undefined ? "" : String(value), xs[i], y, {
            width: widths[i] - 4,
            align: c.align ?? "left",
            lineBreak: false,
            ellipsis: true,
          });
        });
        pdf.y = y + ROW_HEIGHT;
      });

      if (section.note) {
        pdf.moveDown(0.4);
        pdf
          .font("Helvetica-Oblique")
          .fontSize(7)
          .fillColor("#666666")
          .text(section.note, PDF_MARGIN, pdf.y, { width: pageWidth });
        pdf.fillColor("#222222");
      }
      pdf.moveDown(0.8);
    }

    pdf.end();
  });
}

